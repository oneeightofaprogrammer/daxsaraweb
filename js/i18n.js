function applyI18n(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const entry = DAXSARA_I18N[key];
    if (entry && entry[lang]) el.textContent = entry[lang];
  });
  document.querySelectorAll(".nav__lang").forEach(btn => {
    btn.textContent = lang === "fa" ? "EN" : "فا";
    btn.setAttribute("aria-label", lang === "fa" ? "Switch to English" : "تغییر به فارسی");
  });
  try { localStorage.setItem("daxsara-lang", lang); } catch (e) {}
}

function initI18n() {
  let lang = "en";
  try { lang = localStorage.getItem("daxsara-lang") || "en"; } catch (e) {}
  applyI18n(lang);
  document.querySelectorAll(".nav__lang").forEach(btn => {
    btn.addEventListener("click", () => {
      const current = document.documentElement.lang === "fa" ? "fa" : "en";
      applyI18n(current === "fa" ? "en" : "fa");
    });
  });
}
